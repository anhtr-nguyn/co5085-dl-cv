def _my_to_torch_state(sd):
    """Đổi tên key MyMSA -> TorchMSA để copy trọng số."""
    mapping = {
        ".msa.qkv.weight": ".msa.mha.in_proj_weight",
        ".msa.qkv.bias":   ".msa.mha.in_proj_bias",
        ".msa.proj.weight": ".msa.mha.out_proj.weight",
        ".msa.proj.bias":   ".msa.mha.out_proj.bias",
    }
    out = {}
    for k, v in sd.items():
        for a, b in mapping.items():
            if k.endswith(a):
                k = k[: -len(a)] + b
                break
        out[k] = v
    return out

