import torch
import torch.nn as nn

from msa import MyMSA, TorchMSA
from tokenization import build_tokenizer

MSA_CLS = {"my": MyMSA, "torch": TorchMSA}


class EncoderBlock(nn.Module):
    """Pre-LN: x = x + MSA(LN(x)); x = x + FFN(LN(x))."""
    def __init__(self, embed_dim, num_heads, msa_type="my", mlp_ratio=2.0,
                 qkv_bias=True, attn_drop=0.0, proj_drop=0.0, ffn_dropout=0.0):
        super().__init__()
        if msa_type not in MSA_CLS:
            raise ValueError(f"msa_type must be one of {list(MSA_CLS)}")
        hidden = int(embed_dim * mlp_ratio)
        self.ln1 = nn.LayerNorm(embed_dim)
        self.msa = MSA_CLS[msa_type](embed_dim, num_heads, qkv_bias=qkv_bias,
                                     attn_drop=attn_drop)
        self.ln2 = nn.LayerNorm(embed_dim)
        self.ffn = nn.Sequential(
            nn.Linear(embed_dim, hidden),
            nn.GELU(),
            nn.Dropout(ffn_dropout),
            nn.Linear(hidden, embed_dim),
        )

    def forward(self, x):
        x = x + self.msa(self.ln1(x))   # [B, N, C]
        x = x + self.ffn(self.ln2(x))   # [B, N, C]
        return x


class MyTinyViT(nn.Module):
    def __init__(self, embed_dim=128, num_heads=4, num_layers=4, mlp_ratio=2.0,
                 qkv_bias=True, attn_drop=0.0, proj_drop=0.0, ffn_dropout=0.0,
                 emb_dropout=0.0, msa_type="my", tokenizer_type="patch",
                 use_cls_token=True, use_pos_embed=True, num_classes=10,
                 img_size=32, patch_size=4):
        super().__init__()
        self.tokenizer = build_tokenizer(tokenizer_type, embed_dim,
                                         in_channels=3, img_size=img_size,
                                         patch_size=patch_size)
        n_tokens = self.tokenizer.num_tokens + int(use_cls_token)

        if use_cls_token:
            self.cls_token = nn.Parameter(torch.zeros(1, 1, embed_dim))
            nn.init.trunc_normal_(self.cls_token, std=0.02)
        else:
            self.register_parameter("cls_token", None)

        if use_pos_embed:
            self.pos_embed = nn.Parameter(torch.zeros(1, n_tokens, embed_dim))
            nn.init.trunc_normal_(self.pos_embed, std=0.02)
        else:
            self.register_parameter("pos_embed", None)

        self.pos_drop = nn.Dropout(emb_dropout)
        self.encoder = nn.ModuleList([
            EncoderBlock(embed_dim, num_heads, msa_type=msa_type,
                         mlp_ratio=mlp_ratio, qkv_bias=qkv_bias,
                         attn_drop=attn_drop, proj_drop=proj_drop,
                         ffn_dropout=ffn_dropout)
            for _ in range(num_layers)
        ])
        self.ln = nn.LayerNorm(embed_dim)
        self.head = nn.Linear(embed_dim, num_classes)

    def encode(self, tokens):
        """tokens [B, N, C] (đầu ra tokenizer) -> logits [B, num_classes]."""
        x = tokens
        if self.cls_token is not None:
            x = torch.cat([self.cls_token.expand(x.size(0), -1, -1), x], dim=1)
        if self.pos_embed is not None:
            x = x + self.pos_embed
        x = self.pos_drop(x)
        for blk in self.encoder:
            x = blk(x)
        x = self.ln(x)
        x = x[:, 0] if self.cls_token is not None else x.mean(dim=1)
        return self.head(x)

    def forward(self, x):
        return self.encode(self.tokenizer(x))   # [B, 3, 32, 32] -> [B, 10]


def count_params(model, trainable_only=True):
    return sum(p.numel() for p in model.parameters() if p.requires_grad or not trainable_only)

