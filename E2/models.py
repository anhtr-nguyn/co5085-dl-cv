    torch.manual_seed(0)
    crit = nn.CrossEntropyLoss()
    x = torch.randn(32, 3, 32, 32)
    y = torch.randint(0, 10, (32,))

    # 1-4: shape, params, init loss, overfit 1 batch
    for tok in ["patch", "row", "cnn"]:
        counts = {}
        for msa in ["my", "torch"]:
            m = MyTinyViT(msa_type=msa, tokenizer_type=tok)
            assert m(x).shape == (32, 10)
            counts[msa] = count_params(m)
            init_loss = crit(m(x), y).item()

            opt = torch.optim.AdamW(m.parameters(), lr=1e-3)
            m.train()
            for _ in range(200):
                opt.zero_grad()
                loss = crit(m(x), y)
                loss.backward()
                opt.step()
            print(f"{tok:6s} {msa:6s} params={counts[msa]:>8,} "
                  f"tok_params={count_params(m.tokenizer):>8,} "
                  f"init={init_loss:.3f} final={loss.item():.4f}")
        assert counts["my"] == counts["torch"], "my vs torch lệch số tham số"

    # 5: hoán vị token. Không CLS, không pos_embed -> bất biến
    m = MyTinyViT(use_cls_token=False, use_pos_embed=False).eval()
